// Turns the prototype (prototype/Main.dc.html) into app/generated.js for the desktop app.
// Runs automatically before `npm start`, so the desktop app always matches the prototype.
const fs = require('fs');
const path = require('path');

const source = path.join(__dirname, '..', 'prototype', 'Main.dc.html');
const out = path.join(__dirname, 'app', 'generated.js');
const html = fs.readFileSync(source, 'utf8');

const xdc = html.match(/<x-dc>([\s\S]*?)<\/x-dc>/);
if (!xdc) throw new Error('No <x-dc> block found in ' + source);

const helmet = xdc[1].match(/<helmet>([\s\S]*?)<\/helmet>/);
const css = helmet
  ? Array.from(helmet[1].matchAll(/<style>([\s\S]*?)<\/style>/g)).map((m) => m[1]).join('\n')
  : '';
const template = xdc[1].replace(/<helmet>[\s\S]*?<\/helmet>/, '').trim();

const script = html.match(/<script type="text\/x-dc" data-dc-script data-props='([\s\S]*?)'>([\s\S]*?)<\/script>/);
if (!script) throw new Error('No component script found in ' + source);

const decode = (s) => s.replace(/&#39;/g, "'").replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&amp;/g, '&');
const propSpec = JSON.parse(decode(script[1]));
const defaults = {};
for (const [key, spec] of Object.entries(propSpec)) {
  if (!key.startsWith('$') && spec && 'default' in spec) defaults[key] = spec.default;
}

const build = { css, template, code: script[2], defaults };
fs.writeFileSync(out, '// Generated by build.js from prototype/Main.dc.html. Do not edit.\nwindow.PACEY_BUILD = ' + JSON.stringify(build) + ';\n');
console.log('Built app/generated.js from prototype/Main.dc.html');
